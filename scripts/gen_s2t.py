#!/usr/bin/env python3
"""Generate lib/Epub/Epub/SimplifiedToTraditional.h from OpenCC dictionaries.

Source data (Apache-2.0, https://github.com/BYVoid/OpenCC):
    data/dictionary/STCharacters.txt   simplified -> traditional characters
    data/dictionary/STPhrases.txt      simplified -> traditional phrases

Only phrases that a character-wise conversion would get WRONG are kept, which
turns OpenCC's 49k-entry phrase table into a few thousand entries that actually
change the output. Non-BMP codepoints are dropped: the device fonts are BMP-only
subsets, so those glyphs could not be drawn anyway.

    python3 scripts/gen_s2t.py --ascii-dir <dir with stc.txt/stp.txt>
"""

import argparse
import pathlib
import sys


def load_chars(path):
    chars = {}
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        src, dst = parts[0].strip(), parts[1].split()[0].strip()
        if len(src) != 1 or not dst:
            continue
        a, b = ord(src), ord(dst)
        if a > 0xFFFF or b > 0xFFFF:
            continue
        chars[a] = b
    return chars


def charwise(chars, s):
    return "".join(chr(chars.get(ord(c), ord(c))) for c in s)


def load_phrases(path, chars):
    out = []
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        src, dst = parts[0].strip(), parts[1].split()[0].strip()
        if len(src) < 2 or not dst:
            continue
        if any(ord(c) > 0xFFFF for c in src) or any(ord(c) > 0xFFFF for c in dst):
            continue
        if len(src) > 4:            # longer phrases are rare in running text
            continue
        if charwise(chars, src) != dst:
            out.append((src, dst))
    out.sort(key=lambda p: (ord(p[0][0]), -len(p[0]), p[0]))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ascii-dir", required=True, help="directory holding stc.txt and stp.txt")
    ap.add_argument("--out", default="lib/Epub/Epub/SimplifiedToTraditional.h")
    a = ap.parse_args()
    d = pathlib.Path(a.ascii_dir)

    chars = load_chars(d / "stc.txt")
    phrases = load_phrases(d / "stp.txt", chars)
    if not chars:
        sys.exit("no characters loaded")

    # Blob for the phrase strings: one allocation, offsets instead of pointers.
    blob = bytearray()
    index = []
    for src, dst in phrases:
        so = len(blob)
        blob += src.encode("utf-8")
        do = len(blob)
        blob += dst.encode("utf-8")
        index.append((ord(src[0]), so, len(src.encode("utf-8")), do, len(dst.encode("utf-8"))))

    maxlen = max(len(s) for s, _ in phrases)

    lines = []
    lines.append("// GENERATED by scripts/gen_s2t.py -- do not edit by hand.")
    lines.append("//")
    lines.append("// Simplified -> Traditional tables derived from OpenCC (Apache-2.0),")
    lines.append("// https://github.com/BYVoid/OpenCC. Characters are a flat sorted array for")
    lines.append("// binary search; phrases are a UTF-8 blob plus an index sorted by the first")
    lines.append("// codepoint, so a lookup only scans the phrases sharing that first character.")
    lines.append("// Only phrases whose result differs from a character-wise conversion are kept.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace S2T {")
    lines.append(f"inline constexpr int kMaxPhraseChars = {maxlen};")
    lines.append("")
    lines.append(f"// {len(chars)} characters, sorted by the simplified codepoint.")
    lines.append("inline constexpr uint16_t kChars[][2] = {")
    row = []
    for k in sorted(chars):
        row.append(f"{{0x{k:04X},0x{chars[k]:04X}}},")
        if len(row) == 8:
            lines.append("  " + "".join(row))
            row = []
    if row:
        lines.append("  " + "".join(row))
    lines.append("};")
    lines.append("")
    lines.append(f"// {len(phrases)} phrases.")
    # 12 bytes with no padding: offsets first, then the two lengths and the key.
    lines.append("struct Phrase { uint32_t srcOff; uint32_t dstOff; uint16_t first; uint8_t srcLen; uint8_t dstLen; };")
    lines.append("inline constexpr char kBlob[] =")
    for i in range(0, len(blob), 96):
        chunk = blob[i:i + 96]
        s = "".join("\\x%02x" % b for b in chunk)
        lines.append('  "%s"' % s)
    lines.append("  ;")
    lines.append("inline constexpr Phrase kPhrases[] = {")
    row = []
    for first, so, sl, do, dl in index:
        # Field order must match struct Phrase.
        row.append(f"{{{so},{do},0x{first:04X},{sl},{dl}}},")
        if len(row) == 6:
            lines.append("  " + "".join(row))
            row = []
    if row:
        lines.append("  " + "".join(row))
    lines.append("};")
    lines.append("")
    lines.append("}  // namespace S2T")
    lines.append("")

    pathlib.Path(a.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"{a.out}: {len(chars)} chars, {len(phrases)} phrases, blob {len(blob)} bytes, "
          f"source {pathlib.Path(a.out).stat().st_size} bytes")


if __name__ == "__main__":
    main()
